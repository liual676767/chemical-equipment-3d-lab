import { clickBoilEquipment } from './boil-browser-actions.mjs';
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { chromium } from 'playwright-core';
import { browserOptions, webglArgs } from './browser-options.mjs';

const base = process.env.VERIFY_BASE ?? 'http://127.0.0.1:48118/';
const output = 'outputs/verify-p3';
mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ ...browserOptions, headless: true, args: webglArgs });
const report = [];
const distance = (a, b) => Math.hypot(...a.map((value, i) => value - b[i]));

try {
  const errors = [];
  const factory = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  factory.on('pageerror', error => errors.push(String(error)));
  await factory.goto(base + '#/node/P-201');
  const pump = factory.locator('.fi-actions a[href="#/device/pump"]');
  await pump.waitFor();
  await factory.waitForTimeout(850);
  await factory.mouse.move(606, 450);
  await factory.mouse.wheel(0, -220);
  await factory.waitForTimeout(700);
  const origin = await factory.evaluate(() => window.__factoryDebug.view());
  await pump.click();
  await factory.locator('.workbench canvas').waitFor();
  await factory.locator('.back-btn').click();
  await pump.waitFor();
  const restored = await factory.evaluate(() => window.__factoryDebug.view());
  assert.equal(new URL(factory.url()).hash, '#/node/P-201');
  assert.equal(restored.selected, 'P-201');
  assert.ok(distance(origin.pos, restored.pos) < 0.001);
  assert.ok(distance(origin.target, restored.target) < 0.001);
  report.push({ route: 'factory', selected: restored.selected, positionError: distance(origin.pos, restored.pos) });
  await factory.close();

  const boil = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  boil.on('pageerror', error => errors.push(String(error)));
  await boil.goto(base + '#/boil');
  await clickBoilEquipment(boil, 'eq-baghouse');
  const inspect = boil.getByRole('button', { name: '观察设备结构', exact: true });
  await inspect.waitFor();
  await boil.waitForTimeout(850);
  const before = await boil.evaluate(() => ({ selected: window.__boil.traceResult?.rootId, mode: window.__boil.mode, view: window.__boil.view() }));
  await inspect.click();
  const dialog = boil.getByRole('dialog', { name: '布袋除尘器结构观察' });
  await dialog.locator('canvas').waitFor();
  assert.equal(new URL(boil.url()).hash, '#/boil/equipment/eq-baghouse');
  await dialog.getByRole('button', { name: '内部观察', exact: true }).click();
  assert.equal(await dialog.getByRole('button', { name: '内部观察', exact: true }).getAttribute('aria-pressed'), 'true');
  const parts = dialog.getByRole('combobox');
  await parts.selectOption({ label: '灰斗' });
  await boil.screenshot({ path: output + '/boil-baghouse-inspection-1440x900.png' });
  await boil.keyboard.press('Escape');
  await dialog.waitFor({ state: 'hidden' });
  const after = await boil.evaluate(() => ({ selected: window.__boil.traceResult?.rootId, mode: window.__boil.mode, view: window.__boil.view() }));
  assert.equal(before.selected, 'eq-baghouse');
  assert.equal(before.selected, after.selected);
  assert.equal(before.mode, after.mode);
  assert.ok(distance(before.view.position, after.view.position) < 0.001);
  assert.ok(distance(before.view.target, after.view.target) < 0.001);
  await boil.goForward();
  await dialog.waitFor();
  await boil.goBack();
  await dialog.waitFor({ state: 'hidden' });
  report.push({ route: 'boil', mode: after.mode, selected: after.selected, positionError: distance(before.view.position, after.view.position) });
  const progress = boil.getByRole('slider', { name: '流程播放进度' });
  const bar = await progress.boundingBox();
  assert.ok(bar);
  await progress.click({ position: { x: bar.width * 8 / 14, y: bar.height / 2 } });
  if (!(await boil.locator('.boil-detail').isVisible())) await boil.locator('.boil-detail-toggle').click();
  await inspect.waitFor();
  await boil.waitForTimeout(800);
  const step = await progress.getAttribute('aria-valuenow');
  assert.equal(step, '9');
  await inspect.click();
  await dialog.waitFor();
  await dialog.getByRole('button', { name: '返回流程' }).click();
  await dialog.waitFor({ state: 'hidden' });
  assert.equal(await progress.getAttribute('aria-valuenow'), '9');
  assert.equal(await boil.evaluate(() => window.__boil.mode), 'playback');
  report.push({ route: 'boil-playback', step });
  await boil.close();

  const direct = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  direct.on('pageerror', error => errors.push(String(error)));
  await direct.goto(base + '#/boil/equipment/eq-baghouse');
  const narrowDialog = direct.getByRole('dialog', { name: '布袋除尘器结构观察' });
  await narrowDialog.locator('canvas').waitFor();
  await direct.waitForFunction(() => document.querySelector('.boil-inspection-stage canvas')?.height > 350);
  const area = await narrowDialog.locator('canvas').boundingBox();
  await direct.screenshot({ path: output + '/boil-baghouse-inspection-390x844.png' });
  assert.ok(area && area.width * area.height / (390 * 844) > 0.6, JSON.stringify(area));
  await narrowDialog.getByRole('button', { name: '返回流程' }).tap();
  await narrowDialog.waitFor({ state: 'hidden' });
  assert.equal(new URL(direct.url()).hash, '#/boil');
  report.push({ route: 'boil-direct', viewport: [390, 844], modelArea: area.width * area.height / (390 * 844) });
  assert.deepEqual(errors, []);
  writeFileSync(output + '/source-return.json', JSON.stringify(report, null, 2));
  console.log('PASS: factory direct source, same-device boil inspection, history, fallback, touch return');
} finally {
  await browser.close();
}
